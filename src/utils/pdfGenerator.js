import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { formatCurrency } from './formatters';

export function generateQuotationPDF(quotation, items) {
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();

  // Header background
  doc.setFillColor(15, 23, 42);
  doc.rect(0, 0, pageWidth, 45, 'F');

  // Company name
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(24);
  doc.setFont('helvetica', 'bold');
  doc.text('FurnTrack', 14, 22);

  // Subtitle
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.text('Furniture Inventory & Quotation', 14, 32);

  // Quotation title
  doc.setTextColor(30, 41, 59);
  doc.setFontSize(18);
  doc.setFont('helvetica', 'bold');
  doc.text('QUOTATION', 14, 60);

  // Date and customer
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(100, 116, 139);
  const dateStr = new Date(quotation.created_at?.toDate?.() || quotation.created_at).toLocaleDateString('en-IN', {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
  });
  doc.text(`Date: ${dateStr}`, 14, 70);
  doc.text(`Customer: ${quotation.customer_email}`, 14, 78);

  // Divider
  doc.setDrawColor(99, 102, 241);
  doc.setLineWidth(0.5);
  doc.line(14, 84, pageWidth - 14, 84);

  // Items table
  const tableData = items.map((item, idx) => [
    idx + 1,
    item.item_name,
    item.description || '—',
    item.quantity,
    formatCurrency(item.price),
    formatCurrency(item.quantity * item.price),
  ]);

  autoTable(doc, {
    startY: 90,
    head: [['#', 'Item', 'Description', 'Qty', 'Price', 'Total']],
    body: tableData,
    styles: {
      fontSize: 9,
      cellPadding: 6,
      textColor: [30, 41, 59],
    },
    headStyles: {
      fillColor: [99, 102, 241],
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      fontSize: 9,
    },
    alternateRowStyles: {
      fillColor: [241, 245, 249],
    },
    columnStyles: {
      0: { cellWidth: 12, halign: 'center' },
      3: { cellWidth: 18, halign: 'center' },
      4: { cellWidth: 28, halign: 'right' },
      5: { cellWidth: 30, halign: 'right' },
    },
    margin: { left: 14, right: 14 },
  });

  // Total
  const finalY = doc.lastAutoTable.finalY + 10;
  doc.setFillColor(15, 23, 42);
  doc.roundedRect(pageWidth - 90, finalY, 76, 18, 3, 3, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(11);
  doc.setFont('helvetica', 'bold');
  doc.text(`Total: ${formatCurrency(quotation.total_amount)}`, pageWidth - 82, finalY + 12);

  // Footer
  const pageHeight = doc.internal.pageSize.getHeight();
  doc.setFontSize(8);
  doc.setTextColor(148, 163, 184);
  doc.setFont('helvetica', 'normal');
  doc.text('Generated by FurnTrack — Smart Inventory Management', 14, pageHeight - 10);

  return doc;
}

export function downloadQuotationPDF(quotation, items) {
  const doc = generateQuotationPDF(quotation, items);
  doc.save(`Quotation_${quotation.customer_email}_${Date.now()}.pdf`);
}
